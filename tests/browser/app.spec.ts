import { test, expect } from '@playwright/test';
test('create habits, persist entries offline, edit notes, inspect statistics, and archive', async ({ page, context }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Add your first habit', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add your first habit', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Read books');
  await page.getByRole('textbox', { name: 'Question (optional)', exact: true }).fill('Did you read today?');
  await page.getByRole('button', { name: 'Save habit', exact: true }).click();
  await expect(page.getByRole('button', { name: 'View Read books', exact: true })).toBeVisible();
  const todayCell = page.getByRole('button', { name: /^Read books, .*unknown$/ }).last();
  await todayCell.click(); await expect(page.getByRole('button', { name: /^Read books, .*yes$/ }).first()).toBeVisible();
  await page.reload(); await expect(page.getByRole('button', { name: /^Read books, .*yes$/ }).first()).toBeVisible();
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.reload();
  await context.setOffline(true); await page.reload();
  await expect(page.getByRole('button', { name: 'View Read books', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /^Read books, .*yes$/ }).first().click();
  await expect(page.getByRole('button', { name: /^Read books, .*no$/ }).first()).toBeVisible();
  await page.reload(); await expect(page.getByRole('button', { name: /^Read books, .*no$/ }).first()).toBeVisible();
  await context.setOffline(false);
  await page.getByRole('button', { name: 'View Read books', exact: true }).click();
  await expect(page.getByText('Habit strength', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Record today', exact: true }).click();
  await page.getByRole('radio', { name: 'Done', exact: true }).click();
  await page.getByRole('textbox', { name: 'Notes (optional)', exact: true }).fill('Finished a chapter.');
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await page.screenshot({ path: `artifacts/${testInfo.project.name}-detail.png`, fullPage: true });
  await page.getByRole('button', { name: 'Archive', exact: true }).click();
  await page.getByRole('button', { name: 'Back to habits', exact: true }).click();
  await expect(page.getByRole('button', { name: 'View Read books', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Filter and sort habits', exact: true }).click();
  await page.getByRole('radio', { name: 'Archived', exact: true }).click();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await expect(page.getByRole('button', { name: 'View Read books', exact: true })).toBeVisible();
  await page.screenshot({ path: `artifacts/${testInfo.project.name}-list.png`, fullPage: true });
  expect(errors).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
test('numerical tracking, themes, full backup export, and empty-account form', async ({ page }, testInfo) => {
  await page.goto('/'); await page.getByRole('button', { name: 'Add your first habit', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Run');
  await page.getByRole('radio', { name: 'Measurable', exact: true }).click();
  await page.getByRole('textbox', { name: 'Target', exact: true }).fill('5');
  await page.getByRole('textbox', { name: 'Unit', exact: true }).fill('km');
  await page.getByRole('button', { name: 'Save habit', exact: true }).click();
  await page.getByRole('button', { name: /^Run, .*unknown$/ }).first().click();
  await page.getByRole('textbox', { name: 'Value (km)', exact: true }).fill('5.5');
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(page.getByRole('button', { name: /^Run, .*5.5 km$/ }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('radio', { name: 'Dark', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Enable skip days', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export full backup', exact: true }).click();
  const file = await download; expect(file.suggestedFilename()).toBe('habits-backup.json');
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.screenshot({ path: `artifacts/${testInfo.project.name}-dark.png`, fullPage: true });
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Connect a sync account', exact: true }).click();
  await expect(page.getByText('An account is optional.', { exact: false })).toBeVisible();
  await expect(page.getByRole('checkbox', { name: 'Include my local habits in this account', exact: true })).not.toBeChecked();
});
