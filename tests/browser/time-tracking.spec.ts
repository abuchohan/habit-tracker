import { expect, test } from '@playwright/test';
import { addDays } from '../../shared/domain';

test('record, edit and retain time-of-day entries in 24-hour and AM/PM formats', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Add habit', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Daily injection');
  await page.getByRole('radio', { name: 'Time of day', exact: true }).click();
  await expect(page.getByRole('radio', { name: '24-hour', exact: true })).toBeChecked();
  await page.getByRole('button', { name: 'Save habit', exact: true }).click();
  const today = (await page.locator('[data-testid^="date-header-"]').last().getAttribute('data-testid'))!.slice('date-header-'.length);
  const cell = (label: string) => page.getByRole('button', { name: `Daily injection, ${today}, ${label}`, exact: true });
  await cell('unknown').click();
  await expect(page.getByRole('textbox', { name: 'Time (HH:mm)', exact: true })).toHaveValue('');
  await page.getByRole('radio', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Time (HH:mm)', exact: true })).toHaveAttribute('aria-invalid', 'true');
  await page.getByRole('textbox', { name: 'Time (HH:mm)', exact: true }).fill('24:00');
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('00:00 to 23:59');
  await page.getByRole('textbox', { name: 'Time (HH:mm)', exact: true }).fill('00:00');
  await page.getByRole('textbox', { name: 'Notes (optional)', exact: true }).fill('Left side');
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(cell('00:00')).toBeVisible();
  await page.reload();
  await expect(cell('00:00')).toBeVisible();
  await cell('00:00').click();
  await expect(page.getByRole('textbox', { name: 'Time (HH:mm)', exact: true })).toHaveValue('00:00');
  await page.getByRole('textbox', { name: 'Date (YYYY-MM-DD)', exact: true }).fill(addDays(today, -1));
  await expect(page.getByRole('textbox', { name: 'Time (HH:mm)', exact: true })).toHaveValue('');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();

  await page.getByRole('button', { name: 'View Daily injection', exact: true }).click();
  await expect(page.getByText('Recorded today at 00:00', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit habit', exact: true }).click();
  await page.getByRole('radio', { name: '12-hour (AM/PM)', exact: true }).click();
  await page.getByRole('button', { name: 'Save habit', exact: true }).click();
  await expect(page.getByText('Recorded today at 12:00 AM', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Record today', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Time (hh:mm)', exact: true })).toHaveValue('12:00');
  await expect(page.getByRole('radio', { name: 'AM', exact: true })).toBeChecked();
  await page.getByRole('radio', { name: 'PM', exact: true }).click();
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(page.getByText('Recorded today at 12:00 PM', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Back to habits', exact: true }).click();
  await expect(cell('12:00 PM')).toBeVisible();
  await page.screenshot({ path: `artifacts/${testInfo.project.name}-time-habit.png` });
  await cell('12:00 PM').click();
  await page.getByRole('radio', { name: 'Missed', exact: true }).click();
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(cell('no')).toBeVisible();
  await cell('no').click();
  await expect(page.getByRole('textbox', { name: 'Time (hh:mm)', exact: true })).toHaveValue('');
  await page.getByRole('button', { name: 'Use current time', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Time (hh:mm)', exact: true })).toHaveValue(/^\d{1,2}:\d{2}$/);
  await expect(page.getByRole('radio', { name: 'Done', exact: true })).toBeChecked();
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await page.getByRole('button', { name: /^Daily injection, .* (AM|PM)$/ }).click();
  await page.getByRole('radio', { name: 'Skip', exact: true }).click();
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(cell('skip')).toBeVisible();
  await cell('skip').click();
  await page.getByRole('radio', { name: 'Clear', exact: true }).click();
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(cell('unknown')).toBeVisible();
});
